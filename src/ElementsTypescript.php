<?php

namespace Shirahcan\Pml;

/**
 * Renders the element definitions ({@see ElementCatalog}) as the frontend's TypeScript module (PML v3
 * l1-04a). The frontend is a separate deploy and cannot read the backend folder, so it gets a committed,
 * generated copy; `ElementsExportIsCurrentTest` fails the build when that copy is stale, so the two sides
 * cannot drift. Deterministic: the same definitions always render byte-identical output.
 */
final class ElementsTypescript
{
    /**
     * The copy the frontend actually runs (shared program E1, 2026-11-13): the language moved into the shared
     * package `@shirahcan/pml`, which ships its generated module, so the copy that matters is the INSTALLED,
     * pinned package's. A changed `elements.json` fails `ElementsExportIsCurrentTest` until a package version
     * carrying it is released and pinned.
     */
    public const TARGET = 'frontend/node_modules/@shirahcan/pml/src/pml/elements.generated.ts';

    /** Where `pml:export-elements` writes by default: the package's own checkout, beside this repository. */
    public const PACKAGE_SOURCE = '../pml-ui/src/pml/elements.generated.ts';

    public static function targetPath(): string
    {
        return dirname(ElementCatalog::path(), 4).'/'.self::TARGET;
    }

    public static function packageSourcePath(): string
    {
        return dirname(ElementCatalog::path(), 4).'/'.self::PACKAGE_SOURCE;
    }

    public static function render(): string
    {
        $data = ElementCatalog::data();
        $elements = [];

        foreach ($data['elements'] as $name => $element) {
            $props = [];

            foreach ($element['props'] as $key => $def) {
                $out = ['type' => $def['type']];

                if ($def['type'] === 'enum') {
                    $out['values'] = ElementCatalog::enumValues($def);
                }
                if (($def['number'] ?? false) === true) {
                    $out['number'] = true;
                }
                if (isset($def['pattern'])) {
                    $out['pattern'] = $def['pattern'];
                }
                if (($def['compiled'] ?? false) === true) {
                    $out['compiled'] = true;
                }

                $props[$key] = $out;
            }

            $entry = ['container' => $element['container']];
            if (isset($element['category'])) {
                $entry['category'] = $element['category'];
            }
            if (isset($element['holds'])) {
                $entry['holds'] = $element['holds'];
            }
            if (isset($element['children'])) {
                $entry['children'] = $element['children'];
            }
            if (isset($element['parent'])) {
                $entry['parent'] = $element['parent'];
            }
            $entry['props'] = $props === [] ? new \stdClass : $props;
            $elements[$name] = $entry;
        }

        $lines = [
            '// GENERATED by `php artisan pml:export-elements` from backend/resources/pml/elements.json. Do not edit:',
            '// change the JSON and re-run the command. ElementsExportIsCurrentTest fails when this file is stale.',
            '',
            "export type PmlPropType = 'prose' | 'string' | 'enum' | 'bool' | 'url' | 'email' | 'date' | 'anchor' | 'pattern' | 'doc' | 'program';",
            '',
            'export interface PmlPropDef {',
            '  type: PmlPropType;',
            '  /** An enum\'s allowed values. */',
            '  values?: readonly string[];',
            '  /** An enum stored as a whole number (a heading level, a column count). */',
            '  number?: boolean;',
            '  /** A named id shape the backend checks (video_id, form_key). */',
            '  pattern?: string;',
            '  /** Made by the compiler from another prop (the rich text doc); never authored or stored. */',
            '  compiled?: boolean;',
            '}',
            '',
            'export interface PmlElementDef {',
            '  container: boolean;',
            '  /** "inline": a run-level element (strong, link, code...) that sits only inside a holder. */',
            "  category?: 'inline';",
            '  /** "inline": its content is words, text runs and inline elements only (p, strong...). */',
            "  holds?: 'inline';",
            '  /** The only child elements allowed; absent = any. */',
            '  children?: readonly string[];',
            '  /** The only parents allowed: one = directly inside it, several = inside one of them. */',
            '  parent?: readonly string[];',
            '  props: Readonly<Record<string, PmlPropDef>>;',
            '}',
            '',
            '/** The shared value lists (icons, field kinds, gaps, ...). */',
            'export const PML_ENUMS = '.self::literal($data['enums'], 0).' as const;',
            '',
            '/** Every element, in definition order. */',
            'export const ELEMENT_NAMES = '.self::literal(array_keys($elements), 0).' as const;',
            '',
            'export type ElementName = (typeof ELEMENT_NAMES)[number];',
            '',
            '/** The elements that may hold children. */',
            'export const CONTAINER_ELEMENTS = '.self::literal(ElementCatalog::containers(), 0).' as const;',
            '',
            '/** Prop names that are visible words only as a component\'s setting (no element owns them). */',
            'export const COMPONENT_PROSE = '.self::literal($data['component_prose'], 0).' as const;',
            '',
            'export const ELEMENTS: Readonly<Record<ElementName, PmlElementDef>> = '.self::literal($elements, 0).';',
            '',
        ];

        return implode("\n", $lines);
    }

    /** A TS literal: objects one key per line (2-space indent), lists of scalars on one line. */
    private static function literal(mixed $value, int $depth): string
    {
        if (is_bool($value)) {
            return $value ? 'true' : 'false';
        }
        if (is_int($value)) {
            return (string) $value;
        }
        if (is_string($value)) {
            return "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'";
        }

        if ($value instanceof \stdClass) {
            return '{}';
        }

        $value = (array) $value;

        if (array_is_list($value)) {
            return '['.implode(', ', array_map(fn ($v) => self::literal($v, $depth + 1), $value)).']';
        }

        $pad = str_repeat('  ', $depth + 1);
        $lines = [];
        $flat = true;

        foreach ($value as $key => $item) {
            $name = preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', (string) $key) === 1 ? (string) $key : self::literal((string) $key, 0);
            $lines[] = $name.': '.self::literal($item, $depth + 1);
            $flat = $flat && (is_scalar($item) || (is_array($item) && array_is_list($item)));
        }

        if ($lines === []) {
            return '{}';
        }

        // A small object of plain values (a prop's definition) reads best on one line.
        $inline = '{ '.implode(', ', $lines).' }';
        if ($flat && strlen($inline) <= 100) {
            return $inline;
        }

        return "{\n".$pad.implode(",\n".$pad, $lines).",\n".str_repeat('  ', $depth).'}';
    }
}
